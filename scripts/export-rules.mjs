#!/usr/bin/env node
/**
 * Export skills/<name>/SKILL.md into the rule format of other AI tools.
 *
 * Usage:
 *   node scripts/export-rules.mjs --list
 *   node scripts/export-rules.mjs --target claude  --out .
 *   node scripts/export-rules.mjs --target all     --out .exported
 *
 * Targets: claude | agents | copilot | cursor | windsurf | cline | gemini | aider | all
 * No dependencies beyond Node >= 18. Read-only with respect to skills/.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS_DIR = join(ROOT, 'skills');

/** Cursor/Windsurf globs, so the rule attaches to the files it is about. */
const GLOBS = {
  'api-design': ['**/api/**', '**/*Controller*', '**/*controller*', '**/*route*', '**/*routes*', '**/*.proto'],
  'test-strategy': ['**/*test*', '**/*Test*', '**/__tests__/**', '**/*.spec.*'],
  'perf-investigate': [],
  'code-review': [],
  'commit-and-pr': [],
  'refactor-plan': [],
  'debug-repro': [],
  'migration-plan': [],
  'release-notes': [],
};

function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    meta[kv[1]] = kv[2].trim().replace(/^["']|["']$/g, '');
  }
  return { meta, body: text.slice(m[0].length).replace(/^\s+/, '') };
}

function loadSkills() {
  if (!existsSync(SKILLS_DIR)) {
    console.error(`skills directory not found: ${SKILLS_DIR}`);
    process.exit(1);
  }
  return readdirSync(SKILLS_DIR)
    .filter((d) => statSync(join(SKILLS_DIR, d)).isDirectory())
    .filter((d) => existsSync(join(SKILLS_DIR, d, 'SKILL.md')))
    .sort()
    .map((dir) => {
      const raw = readFileSync(join(SKILLS_DIR, dir, 'SKILL.md'), 'utf8');
      const { meta, body } = parseFrontmatter(raw);
      return { dir, name: meta.name || dir, description: meta.description || '', body, raw };
    });
}

const write = (file, content) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, 'utf8');
  return file; // callers log size via readFileSync
};

const withFrontmatter = (fields, body) =>
  `---\n${Object.entries(fields)
    .map(([k, v]) => `${k}: ${typeof v === 'string' ? JSON.stringify(v) : v}`)
    .join('\n')}\n---\n\n${body.trim()}\n`;

const note = (skill, target) =>
  `<!-- generated by dsh-coding-skills (scripts/export-rules.mjs) for ${target}; edit skills/${skill.dir}/SKILL.md instead -->`;

function aggregate(skills, target, title, intro) {
  const index = skills.map((s) => `- \`${s.name}\` — ${s.description}`).join('\n');
  const sections = skills
    .map((s) => `\n---\n\n## ${s.name}\n\n> 何时使用：${s.description}\n\n${s.body.trim()}\n`)
    .join('\n');
  return `${note(skills[0], target)}\n# ${title}\n\n${intro}\n\n## 技能索引\n\n${index}\n${sections}`;
}

const TARGETS = {
  claude(skills, out) {
    // Same layout and frontmatter as this repo: copy verbatim.
    return skills.map((s) => write(join(out, '.claude', 'skills', s.name, 'SKILL.md'), s.raw));
  },
  cursor(skills, out) {
    return skills.map((s) =>
      write(
        join(out, '.cursor', 'rules', `${s.name}.mdc`),
        withFrontmatter(
          { description: s.description, globs: (GLOBS[s.name] || []).join(','), alwaysApply: false },
          s.body,
        ),
      ),
    );
  },
  windsurf(skills, out) {
    return skills.map((s) =>
      write(
        join(out, '.windsurf', 'rules', `${s.name}.md`),
        withFrontmatter({ trigger: 'model_decision', description: s.description }, s.body),
      ),
    );
  },
  cline(skills, out) {
    return skills.map((s) =>
      write(
        join(out, '.clinerules', `${s.name}.md`),
        `# ${s.name}\n\n> 何时使用：${s.description}\n\n${s.body.trim()}\n`,
      ),
    );
  },
  copilot(skills, out) {
    return [
      write(
        join(out, '.github', 'copilot-instructions.md'),
        aggregate(
          skills,
          'github copilot',
          '编程工作流规则',
          '以下是按需参考的工作流规则。常驻上下文成本高，保持简短：先看索引，命中场景再读对应小节。',
        ),
      ),
    ];
  },
  agents(skills, out) {
    return [
      write(
        join(out, 'AGENTS.md'),
        aggregate(
          skills,
          'AGENTS.md',
          '编程工作流规则',
          '按场景选择小节执行，不要一次套用全部流程。',
        ),
      ),
    ];
  },
  aider(skills, out) {
    return [write(join(out, 'CONVENTIONS.md'), aggregate(skills, 'aider', '编程约定与工作流', '按场景取用。'))];
  },
  gemini(skills, out) {
    // Stay slim: import the real files instead of inlining them.
    const imports = skills.map((s) => `@skills/${s.name}/SKILL.md`).join('\n');
    const index = skills.map((s) => `- \`${s.name}\` — ${s.description}`).join('\n');
    return [
      write(
        join(out, 'GEMINI.md'),
        `# 编程工作流规则\n\n按需加载，不要一次套用全部。\n\n## 索引\n\n${index}\n\n## 引入\n\n${imports}\n`,
      ),
    ];
  },
};

function main() {
  const argv = process.argv.slice(2);
  const flag = (name, fallback) => {
    const i = argv.indexOf(`--${name}`);
    return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : fallback;
  };

  if (argv.includes('--list') || argv.length === 0) {
    for (const s of loadSkills()) {
      console.log(`${s.name.padEnd(18)} ${s.description.slice(0, 80)}`);
    }
    if (argv.length === 0) {
      console.error('\nusage: node scripts/export-rules.mjs --target <' + Object.keys(TARGETS).join('|') + '|all> --out <dir>');
    }
    return;
  }

  const target = flag('target', '');
  const out = resolve(flag('out', '.'));
  const names = target === 'all' ? Object.keys(TARGETS) : [target];

  for (const name of names) {
    if (!TARGETS[name]) {
      console.error(`unknown target: ${name}\navailable: ${Object.keys(TARGETS).join(', ')}, all`);
      process.exit(1);
    }
  }

  const skills = loadSkills();
  console.log(`source: ${SKILLS_DIR} (${skills.length} skills)`);
  console.log(`out:    ${out}\n`);

  for (const name of names) {
    const files = TARGETS[name](skills, out);
    for (const f of files) {
      const size = readFileSync(f, 'utf8').length;
      const warn = size > 60000 ? '  ⚠ large: some tools truncate long rule files' : '';
      console.log(`  ${name.padEnd(9)} ${String(size).padStart(7)}ch  ${f}${warn}`);
    }
  }
  console.log('\ndone. verify the rules actually load: docs/using-with-other-ai-tools.md §4');
}

main();
